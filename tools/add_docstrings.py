def _indent(text: str, prefix: str) -> str:
    """Добавляет префикс к каждой непустой строке."""
    return "\n".join(prefix + line if line.strip() else "" for line in text.split("\n"))


def build_docstring(summary: str, params: dict[str, str], returns: str) -> str:
    """Собирает докстринг в стиле Google."""
    lines = [summary, ""]
    if params:
        lines.append("Args:")
        for name, description in params.items():
            lines.append(f"    {name}: {description}")
        lines.append("")
    lines.append("Returns:")
    lines.append(f"    {returns}")
    lines.append("")
    lines.append(RAISES)
    return "\n".join(lines)


def _default_param_description(name: str) -> str | None:
    """Описание параметра из общих: используется, если оно не задано явно."""
    return COMMON_PARAMS.get(name)


class Collector:
    """Собирает правки исходника: где вставить докстринг и какой именно."""

    def __init__(self, module: str) -> None:
        self.module = module
        #: Правки вида ``(начало, конец, текст)``: замена строк [начало, конец).
        self.edits: list[tuple[int, int, str]] = []
        #: Методы без аннотации возврата: ``(имя, аннотация)``.
        self.annotations: list[tuple[str, str]] = []
        #: Методы с неверной аннотацией: ``(имя, правильная аннотация)``.
        self.reannotations: list[tuple[str, str]] = []
        #: Нужен ли модулю импорт псевдонима ``RacRecord``.
        self.needs_alias = False
        self.undocumented: list[str] = []
        self.missing_params: list[str] = []


def _walk_class(
    node: ast.ClassDef,
    collector: Collector,
    path: tuple[str, ...] = (),
) -> None:
    """Рекурсивно обходит класс и вложенные классы, вставляя докстринги."""
    current = (*path, node.name)
    owner = ".".join(current)

    if not path:
        text = CLASS_DOCSTRINGS.get(collector.module)
    else:
        text = NESTED_CLASS_DOCSTRINGS.get(owner)
    if text:
        indent = " " * (node.col_offset + 4)
        _set_docstring(collector, node, text, indent)

    for child in node.body:
        if isinstance(child, ast.ClassDef):
            _walk_class(child, collector, current)
        elif isinstance(child, ast.FunctionDef):
            _handle(collector, child, owner, current)


