def _body_start(node: ast.ClassDef | ast.FunctionDef) -> int:
    """Номер строки (1-based), с которой начинается тело класса или функции.

    Опираться на ``node.lineno`` нельзя: у метода с многострочной сигнатурой
    ``def`` занимает несколько строк, а ``body[0].lineno`` декорированного
    элемента указывает на ``def``, а не на ``@staticmethod``. Поэтому берём
    позицию первой инструкции тела и позицию после декораторов — что позже.
    """
    if isinstance(node, ast.ClassDef):
        return node.lineno + 1
    candidates = [node.body[0].lineno]
    if node.decorator_list:
        candidates.append(max(d.lineno for d in node.decorator_list) + 1)
    return max(candidates)


def _set_docstring(
    collector: Collector,
    node: ast.ClassDef | ast.FunctionDef,
    text: str,
    indent: str,
) -> None:
    """Готовит правку докстринга для класса или метода."""
    literal = f'{indent}"""{_indent(text, indent).lstrip()}\n{indent}"""'
    span = _docstring_span(node)
    if span is None:
        start = _body_start(node)
        collector.edits.append((start - 1, start - 1, literal))
    else:
        collector.edits.append((span[0] - 1, span[1], literal))


def _docstring_span(node: ast.ClassDef | ast.FunctionDef) -> tuple[int, int] | None:
    """Возвращает границы существующего докстринга в номерах строк (1-based).

    Это делает вставку идемпотентной: повторный прогон заменяет докстринг, а не
    добавляет второй.
    """
    if not node.body:
        return None
    first = node.body[0]
    if (
        isinstance(first, ast.Expr)
        and isinstance(first.value, ast.Constant)
        and isinstance(first.value.value, str)
    ):
        return first.lineno, first.end_lineno or first.lineno
    return None


def _return_annotation(method: str, returns: str) -> str:
    """Определяет аннотацию возвращаемого значения по тексту секции Returns.

    Аннотации нужны не только читателю: mkdocstrings (griffe) считает отсутствие
    аннотации при наличии секции ``Returns`` предупреждением, а сборка
    документации идёт в strict-режиме и падает на предупреждениях.
    """
    # Методы создания возвращают идентификатор объекта, а не запись RAC —
    # проверка идёт первой, потому что их докустринг тоже содержит ``str:``.
    if method in ID_RETURNING_METHODS:
        return "str"
    if returns.startswith("str"):
        return "str"
    if returns == RETURNS_LIST:
        return ANNOTATIONS["RETURNS_LIST"]
    if returns == RETURNS_DICT:
        return ANNOTATIONS["RETURNS_DICT"]
    if returns == RETURNS_NONE:
        return ANNOTATIONS["RETURNS_NONE"]
    return ANNOTATIONS["RETURNS_DICT"]


def _signature_close(node: ast.FunctionDef, lines: list[str]) -> int:
    """Возвращает индекс строки (0-based), на которой закрывается сигнатура.

    Ищем строку, которая начинается с ``)`` и заканчивается на ``:``. Так
    выглядят и сигнатура без аннотации (``):``), и уже аннотированная
    (``) -> list[RacRecord]:``) — иначе повторный прогон не нашёл бы сигнатуру и
    аннотация не обновилась бы.

    Поиск ограничен телом функции. Без этой границы у однострочной сигнатуры
    сканер уходил вниз по файлу и находил закрывающую скобку **следующего**
    метода, из-за чего аннотация записывалась чужому методу.
    """
    limit = node.body[0].lineno - 1 if node.body else node.end_lineno or node.lineno
    for index in range(node.lineno - 1, limit):
        stripped = lines[index].lstrip()
        if stripped.startswith(")") and stripped.rstrip().endswith(":"):
            return index
    return node.lineno - 1


def _handle(
    collector: Collector,
    node: ast.FunctionDef,
    owner: str,
    path: tuple[str, ...],
) -> None:
    """Готовит правки для метода: аннотацию возврата и докстринг."""
    table = DOCSTRINGS.get(collector.module, {})
    methods = table.get(owner) or table.get(path[-1])
    if methods is None or node.name not in methods:
        collector.undocumented.append(f"{owner}.{node.name}")
        return

    summary, params, returns = methods[node.name]
    signature_params = [a.arg for a in node.args.args if a.arg != "session"]
    described: dict[str, str] = {}
    for name in signature_params:
        if name in params:
            described[name] = params[name]
            continue
        fallback = COMMON_PARAMS.get(name)
        if fallback is None:
            collector.missing_params.append(f"{owner}.{node.name}:{name}")
            fallback = "Описание не задано."
        described[name] = fallback

    docstring = build_docstring(summary, described, returns)
    indent = " " * (node.col_offset + 4)
    _set_docstring(collector, node, docstring, indent)

    if node.returns is None:
        collector.annotations.append((node.name, _return_annotation(node.name, returns)))
    elif ast.unparse(node.returns) != _return_annotation(node.name, returns):
        # Аннотация уже есть, но неверная (например, её вывели из устаревшего
        # описания) — помечаем на замену.
        collector.reannotations.append(
            (node.name, _return_annotation(node.name, returns))
        )

    # Флаг выставляем по факту наличия RacRecord в аннотации, а не только при её
    # добавлении: иначе при повторном прогоне нужные импорты не восстановятся.
    annotation = _return_annotation(node.name, returns)
    if "RacRecord" in annotation:
        collector.needs_alias = True


def _collect_functions(node: ast.AST) -> list[ast.FunctionDef]:
    """Собирает функции класса в порядке исходника.

    ``ast.walk`` здесь не годится: он обходит дерево в ширину, поэтому
    одноимённые методы (``Cluster.list`` и ``Cluster.Admin.list``) оказывались
    в списке в порядке, не совпадающем с исходником, и аннотация попадала не в
    тот метод.
    """
    functions: list[ast.FunctionDef] = []
    for child in node.body:  # type: ignore[attr-defined]
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            functions.append(child)
        elif isinstance(child, ast.ClassDef):
            functions.extend(_collect_functions(child))
    return functions


def process_module(path: Path) -> tuple[str, list[str], list[str]]:
    """Возвращает новый исходник модуля и списки проблем."""
    source = path.read_text(encoding="utf-8")
    collector = Collector(path.stem)

    module_docstring = MODULE_DOCSTRINGS.get(path.stem)
    tree = ast.parse(source)
    functions: list[ast.FunctionDef] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            _walk_class(node, collector)
            functions.extend(_collect_functions(node))

    lines = source.split("\n")
    functions_by_name: dict[str, list[ast.FunctionDef]] = {}
    for function in functions:
        functions_by_name.setdefault(function.name, []).append(function)

    # Аннотации возврата проставляем до правок тела, чтобы не сбить нумерацию.
    for name, annotation in [*collector.annotations, *collector.reannotations]:
        matching = functions_by_name.get(name)
        if not matching:
            continue
        close = _signature_close(matching[0], lines)
        line = lines[close]
        if "->" in line:
            # В строке уже есть аннотация: оставляем часть до «->» как есть,
            # она уже содержит закрывающую скобку с нужным отступом.
            head, _, _ = line.partition("->")
            lines[close] = f"{head.rstrip()} -> {annotation}:"
        else:
            lines[close] = line.replace("):", f") -> {annotation}:", 1)
        # Обработанный метод больше не должен претендовать на следующие
        # аннотации с тем же именем.
        matching.pop(0)

    # Правки тела — с конца, чтобы не сбить нумерацию строк.
    for start, end, literal in sorted(collector.edits, reverse=True):
        lines[start:end] = [literal]

    if module_docstring and not _has_module_docstring(source):
        lines[0:0] = [f'"""{module_docstring}"""', ""]

    # Отложенные аннотации обязательны: в классах есть методы с именами
    # `list` и `dict`, которые затеняют встроенные типы, и аннотация вида
    # `-> list[RacRecord]` падала бы с TypeError при вычислении.
    if collector.needs_alias:
        # `from __future__` обязан идти первым импортом модуля, поэтому
        # вставляем его отдельно от отсортированного блока — и только если его
        # ещё нет, иначе повторный прогон добавил бы дубль.
        future_import = "from __future__ import annotations"
        if future_import not in lines:
            for index, line in enumerate(lines):
                if line.startswith("from "):
                    lines.insert(index, future_import)
                    break
        _insert_import(lines, "from .._shared import RacRecord")

    return "\n".join(lines), collector.undocumented, collector.missing_params


def _insert_import(lines: list[str], statement: str) -> None:
    """Вставляет импорт в блок и приводит блок к виду, который требует ruff.

    Помимо самой вставки это добавляет пустую строку после
    ``from __future__ import annotations`` и сортирует имена внутри
    ``from X import a, b`` — ровно то, что проверяет правило I001.
    """
    start = 0
    while start < len(lines) and not lines[start].startswith(("import ", "from ")):
        start += 1
    end = start
    while end < len(lines) and (
        lines[end].startswith(("import ", "from ")) or not lines[end].strip()
    ):
        end += 1

    block = [_sort_names(line) for line in lines[start:end] if line.strip()]
    if statement not in block:
        block.append(statement)

    def sort_key(line: str) -> tuple[int, int, str]:
        if line.startswith("import "):
            return (1, 0, line)
        after_from = line.split(" ", 1)[1]
        if after_from.startswith("__future__"):
            return (0, 0, "")
        depth = len(after_from) - len(after_from.lstrip("."))
        if depth:
            return (2, -depth, line)
        return (3, 0, line)

    ordered = sorted(block, key=sort_key)
    if any(line.startswith("from __future__") for line in ordered):
        index = max(i for i, line in enumerate(ordered) if line.startswith("from __future__"))
        ordered.insert(index + 1, "")

    # Сохраняем ровно столько пустых строк после последнего импорта, сколько было:
    # считаем именно хвостовые, а не все пустые в блоке (одна пустая строка
    # разделяет `from __future__` и остальные импорты и хвостовой не является).
    trailing = 0
    for line in reversed(lines[start:end]):
        if line.strip():
            break
        trailing += 1
    lines[start:end] = [*ordered, *([""] * max(trailing, 1))]


def _sort_names(line: str) -> str:
    """Сортирует имена в ``from X import a, b``; импорты с ``as`` не трогает."""
    if " import " not in line or " as " in line or "(" in line:
        return line
    head, _, names = line.partition(" import ")
    if "," not in names:
        return line
    return f"{head} import {', '.join(sorted(part.strip() for part in names.split(',')))}"


def _has_module_docstring(source: str) -> bool:
    """Есть ли у модуля докстринг."""
    tree = ast.parse(source)
    return ast.get_docstring(tree) is not None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="только проверить покрытие")
    args = parser.parse_args(argv)

    undocumented: list[str] = []
    missing: list[str] = []
    changed = 0

    modules = sorted(p for p in SYNC_CMD.glob("*.py") if p.stem != "command")
    for path in modules:
        if path.stem != "command" and path.stem not in DOCSTRINGS:
            continue
        new_source, undoc, miss = process_module(path)
        undocumented.extend(f"{path.stem}:{name}" for name in undoc)
        missing.extend(f"{path.stem}:{name}" for name in miss)
        if new_source != path.read_text(encoding="utf-8"):
            changed += 1
            if not args.check:
                path.write_text(new_source, encoding="utf-8")
                print(f"обновлён: {path.relative_to(REPO_ROOT)}")

    missing_modules = [
        path.stem
        for path in modules
        if path.stem in MODULE_DOCSTRINGS
        and not _has_module_docstring(path.read_text(encoding="utf-8"))
    ]

    if missing_modules:
        print("Нет докстринга у модулей:", file=sys.stderr)
        for name in missing_modules:
            print(f"  - {name}", file=sys.stderr)

    if undocumented:
        print("Нет описания для методов:", file=sys.stderr)
        for name in undocumented:
            print(f"  - {name}", file=sys.stderr)
    if missing:
        print("Нет описания для параметров:", file=sys.stderr)
        for name in missing:
            print(f"  - {name}", file=sys.stderr)

    if args.check:
        if changed:
            print(
                f"Докстринги не актуальны в {changed} модулях. "
                "Запустите: python tools/add_docstrings.py",
                file=sys.stderr,
            )
            return 1
        if undocumented or missing or missing_modules:
            return 1
        print("Все методы задокументированы.")
        return 0

    print(f"Модулей обновлено: {changed}")
    return 1 if (undocumented or missing or missing_modules) else 0


if __name__ == "__main__":
    raise SystemExit(main())
